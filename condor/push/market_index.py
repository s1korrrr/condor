"""Fleet Market index for the Live Activity headline: a port of Swift ``FleetMarketIndex.build``.

Owner of the maths: ``mobile/rsibot-ios/Sources/RSIBotMobileCore/Composite/FleetMarketIndex.swift``
(rsibot workspace), with ``ChartSeries``/``ChartCandle``/``RecordedTime`` decoding from
``Drilldown/DrilldownModels.swift``. This module ports only what the Live Activity content needs:
closed-candle filtering, the longest series per pair (first input wins ties), the stale-baseline
loop, base-100 normalisation, the equal-weight mean with a 1.5-step carry, and the staleness
rule. Issues, pair lines for charts and fill projection are not ported.

The headline (value, change, spark) ports Swift ``FleetMarketHeadline``
(``Composite/FleetMarketHeadline.swift``).

Parity: ``tests/fixtures/fleet_market_index_parity_v1.json`` is byte-identical to the iOS
fixture of the same name; its expected values are generated by the Swift code. Change the Swift
owner first, regenerate the fixture there, copy it here, then follow in this port.

Bit-for-bit choices, so the numbers equal the app's:

* times are Swift ``Date`` values: seconds since 2001-01-01 as doubles, built exactly as
  ``Date(timeIntervalSince1970:)`` does (``t1970 - 978307200``); every comparison and
  difference uses them;
* a pair value is ``close / anchor * 100`` evaluated left to right;
* sums are explicit left-to-right float loops in requested pair order (never ``sum``/``fsum``);
* a series that Swift's ``JSONDecoder`` would reject (wrong types, an unparseable time) is
  rejected here as a whole (``decode_series`` raises), as the app then has no input for it.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from datetime import datetime
from decimal import ROUND_HALF_UP, Decimal
from typing import Any, Mapping, Sequence

REFERENCE_DATE_1970 = 978307200.0  # Date.timeIntervalBetween1970AndReferenceDate
STALE_FRESHNESS = frozenset({"stale", "offline", "unavailable", "clock_skew"})
_INTERVAL_NAMES = {60: "1m", 300: "5m", 900: "15m"}


def date(t1970: float) -> float:
    """A Swift ``Date(timeIntervalSince1970:)`` as its stored reference-date double."""
    return float(t1970) - REFERENCE_DATE_1970


def since1970(value: float) -> float:
    """``Date.timeIntervalSince1970`` of a stored reference-date double."""
    return value + REFERENCE_DATE_1970


# --------------------------------------------------------------------------- decoding


def _digits(raw: str, start: int, count: int) -> int | None:
    if start + count > len(raw):
        return None
    value = 0
    for char in raw[start : start + count]:
        if not "0" <= char <= "9":
            return None
        value = value * 10 + (ord(char) - 48)
    return value


def _canonical(raw: str) -> float | None:
    """``RecordedTime.canonical``: ``YYYY-MM-DDTHH:MM:SS[.f{1,3}](Z|±HH:MM)`` without a formatter."""
    if not raw.isascii():
        return None
    b = raw
    if (
        len(b) < 20
        or b[4] != "-"
        or b[7] != "-"
        or b[10] != "T"
        or b[13] != ":"
        or b[16] != ":"
    ):
        return None
    year, month, day = _digits(b, 0, 4), _digits(b, 5, 2), _digits(b, 8, 2)
    hour, minute, second = _digits(b, 11, 2), _digits(b, 14, 2), _digits(b, 17, 2)
    if None in (year, month, day, hour, minute, second):
        return None
    if (
        year < 1970
        or not 1 <= month <= 12
        or hour >= 24
        or minute >= 60
        or second >= 60
    ):
        return None
    leap = year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)
    month_days = [31, 29 if leap else 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31][
        month - 1
    ]
    if not 1 <= day <= month_days:
        return None
    index = 19
    milliseconds = 0
    if b[index] == ".":
        count = 0
        index += 1
        while index < len(b) and count < 4:
            digit = _digits(b, index, 1)
            if digit is None:
                break
            milliseconds = milliseconds * 10 + digit
            count += 1
            index += 1
        if not 1 <= count <= 3:
            return None
        for _ in range(count, 3):
            milliseconds *= 10
    if index == len(b) - 1 and b[index] == "Z":
        offset = 0
    elif index == len(b) - 6 and b[index] in "+-" and b[index + 3] == ":":
        oh, om = _digits(b, index + 1, 2), _digits(b, index + 4, 2)
        if oh is None or om is None or oh >= 24 or om >= 60:
            return None
        offset = (oh * 3600 + om * 60) * (-1 if b[index] == "-" else 1)
    else:
        return None
    y = year - 1 if month <= 2 else year
    era = y // 400  # y >= 1969: Swift's truncating division equals floor division here
    year_of_era = y - era * 400
    day_of_year = (153 * (month + (-3 if month > 2 else 9)) + 2) // 5 + day - 1
    day_of_era = year_of_era * 365 + year_of_era // 4 - year_of_era // 100 + day_of_year
    days = era * 146_097 + day_of_era - 719_468
    seconds = days * 86_400 + hour * 3600 + minute * 60 + second - offset
    return date(float(seconds) + float(milliseconds) / 1000)


def parse_recorded_time(raw: Any) -> float | None:
    """``RecordedTime.parse`` as a reference-date double; None for an ambiguous or invalid stamp.

    The canonical reporting shape is ported exactly. Other shapes fall back, as in Swift, to an
    ISO-8601 parse that requires an explicit offset (Python's parser, not Apple's formatter: the
    reporting sources do not send those shapes).
    """
    if not isinstance(raw, str) or not raw:
        return None
    parsed = _canonical(raw)
    if parsed is not None:
        return parsed
    try:
        stamp = datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except ValueError:
        return None
    if stamp.tzinfo is None or "T" not in raw:
        return None
    return date(stamp.timestamp())


@dataclass(frozen=True)
class Candle:
    time: float  # reference-date double
    close: float


@dataclass(frozen=True)
class Series:
    """The fields of Swift ``ChartSeries`` the index reads."""

    ok: bool
    pair: str | None
    bot_name: str | None
    interval: str | None
    candles: tuple[Candle, ...]
    freshness_state: str | None
    source_age_seconds: float | None
    coverage_status: str | None = None
    coverage_truncated: bool | None = None

    @property
    def is_partial(self) -> bool:
        return (
            self.coverage_status in ("partial", "unavailable")
            or self.coverage_truncated is True
        )


class SeriesDecodeError(ValueError):
    """Swift's ``JSONDecoder`` would reject this chart response."""


def _optional(raw: Mapping[str, Any], key: str, kind: type | tuple[type, ...]) -> Any:
    value = raw.get(key)
    if value is None:
        return None
    if isinstance(value, bool) and kind is not bool:
        raise SeriesDecodeError(key)
    if not isinstance(value, kind):
        raise SeriesDecodeError(key)
    return value


def _number(raw: Mapping[str, Any], key: str, *, required: bool) -> float | None:
    value = raw.get(key)
    if value is None:
        if required:
            raise SeriesDecodeError(key)
        return None
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise SeriesDecodeError(key)
    number = float(value)
    if not math.isfinite(number):
        raise SeriesDecodeError(key)
    return number


def _strings(raw: Mapping[str, Any], key: str) -> list[str]:
    value = raw.get(key)
    if value is None:
        return []
    if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
        raise SeriesDecodeError(key)
    return value


def decode_series(raw: Any) -> Series:
    """``ChartSeries.init(from:)``: raises ``SeriesDecodeError`` where Swift decoding throws."""
    if not isinstance(raw, Mapping):
        raise SeriesDecodeError("body")
    status = _optional(raw, "status", str)
    for key in ("message", "pair", "interval", "bot_name"):
        _optional(raw, key, str)
    candles: list[Candle] = []
    raw_candles = raw.get("candles")
    if raw_candles is not None:
        if not isinstance(raw_candles, list):
            raise SeriesDecodeError("candles")
        for item in raw_candles:
            if not isinstance(item, Mapping) or not isinstance(
                item.get("timestamp"), str
            ):
                raise SeriesDecodeError("candle timestamp")
            stamp = parse_recorded_time(item["timestamp"])
            if stamp is None:
                raise SeriesDecodeError("candle timestamp")
            for key in ("open_price", "high_price", "low_price"):
                _number(item, key, required=True)
            candles.append(Candle(stamp, _number(item, "close_price", required=True)))
    raw_markers = raw.get("event_markers")
    if raw_markers is not None:
        if not isinstance(raw_markers, list):
            raise SeriesDecodeError("event_markers")
        for item in raw_markers:
            if not isinstance(item, Mapping):
                raise SeriesDecodeError("marker")
            plot = _optional(item, "plot_timestamp", str)
            stamp = plot if plot is not None else item.get("timestamp")
            if not isinstance(stamp, str) or parse_recorded_time(stamp) is None:
                raise SeriesDecodeError("marker timestamp")
            for key in ("marker_group", "marker_type", "side", "label", "reference_id"):
                _optional(item, key, str)
    coverage = raw.get("coverage")
    if coverage is not None and not isinstance(coverage, Mapping):
        raise SeriesDecodeError("coverage")
    coverage = coverage or {}
    coverage_status = _optional(coverage, "status", str)
    truncated = _optional(coverage, "truncated", bool)
    _strings(coverage, "reasons")
    _strings(coverage, "reason_messages")
    _optional(coverage, "source", str)
    freshness = _optional(raw, "freshness_state", str)
    if freshness is None:
        freshness = _optional(coverage, "freshness_state", str)
    else:
        _optional(coverage, "freshness_state", str)
    if freshness is None and (coverage_status or "").lower() in STALE_FRESHNESS:
        freshness = coverage_status
    ages = [
        age
        for age in (
            _number(raw, "source_age_seconds", required=False),
            _number(coverage, "source_age_seconds", required=False),
        )
        if age is not None and age >= 0
    ]
    return Series(
        ok=status == "ok",
        pair=raw.get("pair"),
        bot_name=raw.get("bot_name"),
        interval=raw.get("interval"),
        candles=tuple(candles),
        freshness_state=freshness,
        source_age_seconds=max(ages) if ages else None,
        coverage_status=coverage_status,
        coverage_truncated=truncated,
    )


# --------------------------------------------------------------------------- index


@dataclass(frozen=True)
class Input:
    """``FleetMarketInput``: one pair response with its request identity and receipt clock."""

    bot: str
    pair: str
    series: Series
    interval_seconds: int
    received_at: float  # reference-date double


@dataclass(frozen=True)
class Index:
    mean: tuple[tuple[float, float], ...]  # (reference-date time, value)
    baseline_time: float | None
    pairs: tuple[str, ...]  # pairs with a line, in requested order
    requested: tuple[str, ...]
    missing_pairs: tuple[str, ...]
    interval_seconds: int
    latest_closed_time: float | None
    oldest_receipt_time: float | None
    reported_source_age_seconds: float | None
    has_explicit_stale_source: bool
    built_at: float

    def source_age_seconds(self, now: float) -> float | None:
        if self.latest_closed_time is None or not math.isfinite(now):
            return None
        candle_age = max(0.0, now - self.latest_closed_time)
        receipt_age = (
            0.0
            if self.oldest_receipt_time is None
            else max(0.0, now - self.oldest_receipt_time)
        )
        reported_age = (self.reported_source_age_seconds or 0.0) + max(
            0.0, now - self.built_at
        )
        return max(candle_age, max(receipt_age, reported_age))

    def is_stale(self, now: float) -> bool:
        if self.has_explicit_stale_source or self.missing_pairs:
            return True
        age = self.source_age_seconds(now)
        if age is None:
            return True
        return age > float(self.interval_seconds) * 1.5


def _unique(values: Sequence[str]) -> list[str]:
    seen: set[str] = set()
    out = []
    for value in values:
        if value and value not in seen:
            seen.add(value)
            out.append(value)
    return out


def _last_at_or_before(candles: Sequence[Candle], time: float) -> Candle | None:
    for candle in reversed(candles):
        if candle.time <= time:
            return candle
    return None


def _shared_step(chosen: Mapping[str, tuple[Input, list[Candle]]]) -> int:
    intervals = [source.interval_seconds for source, _ in chosen.values()]
    return max(max(intervals) if intervals else 60, 1)


def build(inputs: Sequence[Input], expected_pairs: Sequence[str], now: float) -> Index:
    """``FleetMarketIndex.build`` (the parts the headline needs). ``now`` is a reference date."""
    requested = _unique(expected_pairs)
    wanted = set(requested)
    explicit_stale = False
    candidates: dict[str, list[tuple[Input, list[Candle]]]] = {}
    for item in inputs:
        if item.pair not in wanted:
            continue
        if not 0 < item.interval_seconds <= 86_400:
            continue
        series = item.series
        if series.pair is not None and series.pair != item.pair:
            continue
        if series.bot_name is not None and series.bot_name != item.bot:
            continue
        if series.interval is not None and series.interval != _INTERVAL_NAMES.get(
            item.interval_seconds
        ):
            continue
        if not series.ok:
            continue
        cutoff = min(now, item.received_at)
        by_time: dict[float, Candle] = {}
        for candle in series.candles:
            if not (
                math.isfinite(since1970(candle.time))
                and math.isfinite(candle.close)
                and candle.close > 0
            ):
                continue
            if candle.time + float(item.interval_seconds) > cutoff:
                continue  # not closed when it was received
            by_time[candle.time] = candle  # a duplicate time: the last one wins
        candles = sorted(by_time.values(), key=lambda c: c.time)
        if not candles:
            continue
        candidates.setdefault(item.pair, []).append((item, candles))

    chosen: dict[str, tuple[Input, list[Candle]]] = {}
    for pair in requested:
        for candidate in candidates.get(pair, []):
            if pair not in chosen or len(candidate[1]) > len(chosen[pair][1]):
                chosen[pair] = candidate

    shared_step = _shared_step(chosen)
    baseline: float | None = None
    while chosen:
        baseline = max(candles[0].time for _, candles in chosen.values())
        carry = float(shared_step) * 1.5
        too_old = []
        for pair, (_, candles) in chosen.items():
            anchor = _last_at_or_before(candles, baseline)
            if anchor is None or not baseline - anchor.time <= carry:
                too_old.append(pair)
        if not too_old:
            break
        for pair in too_old:
            del chosen[pair]
        shared_step = _shared_step(chosen)

    for source, _ in chosen.values():
        if (source.series.freshness_state or "").lower() in STALE_FRESHNESS:
            explicit_stale = True

    if baseline is None or not chosen:
        receipts = [item.received_at for item in inputs]
        return Index(
            mean=(),
            baseline_time=None,
            pairs=(),
            requested=tuple(requested),
            missing_pairs=tuple(requested),
            interval_seconds=shared_step,
            latest_closed_time=None,
            oldest_receipt_time=min(receipts) if receipts else None,
            reported_source_age_seconds=None,
            has_explicit_stale_source=explicit_stale,
            built_at=now,
        )

    carry = float(shared_step) * 1.5
    lines: list[tuple[str, list[tuple[float, float]]]] = []
    for pair in requested:
        if pair not in chosen:
            continue
        _, candles = chosen[pair]
        anchor = _last_at_or_before(candles, baseline)
        if anchor is None or not (math.isfinite(anchor.close) and anchor.close > 0):
            continue
        points = [(baseline, 100.0)]
        for candle in candles:
            if not candle.time > baseline:
                continue
            value = candle.close / anchor.close * 100
            if not (math.isfinite(value) and value > 0):
                continue
            points.append((candle.time, value))
        lines.append((pair, points))

    mean = _equal_weight_mean([points for _, points in lines], carry)
    latest_closed = min(
        candles[-1].time + float(source.interval_seconds)
        for source, candles in chosen.values()
    )
    oldest_receipt = min(source.received_at for source, _ in chosen.values())
    reported = [
        age + max(0.0, now - source.received_at)
        for source, _ in chosen.values()
        if (age := source.series.source_age_seconds) is not None
        and math.isfinite(age)
        and age >= 0
    ]
    return Index(
        mean=tuple(mean),
        baseline_time=baseline,
        pairs=tuple(pair for pair, _ in lines),
        requested=tuple(requested),
        missing_pairs=tuple(pair for pair in requested if pair not in chosen),
        interval_seconds=shared_step,
        latest_closed_time=latest_closed,
        oldest_receipt_time=oldest_receipt,
        reported_source_age_seconds=max(reported) if reported else None,
        has_explicit_stale_source=explicit_stale,
        built_at=now,
    )


def _equal_weight_mean(
    lines: Sequence[Sequence[tuple[float, float]]], carry: float
) -> list[tuple[float, float]]:
    if not lines:
        return []
    times = sorted({time for points in lines for time, _ in points})
    cursors = [0] * len(lines)
    result: list[tuple[float, float]] = []
    for time in times:
        total = 0.0
        count = 0
        for index, points in enumerate(lines):
            while (
                cursors[index] + 1 < len(points)
                and points[cursors[index] + 1][0] <= time
            ):
                cursors[index] += 1
            point_time, value = points[cursors[index]]
            if not (point_time <= time and time - point_time <= carry):
                continue
            total += value  # left to right, in requested pair order
            count += 1
        if count == len(lines):
            value = total / float(count)
            if math.isfinite(value):
                result.append((time, value))
    return result


# --------------------------------------------------------------------------- headline
# Port of Swift ``FleetMarketHeadline`` (Composite/FleetMarketHeadline.swift), same parity fixture.

SPARK_BUCKET_MS = 30 * 60 * 1000  # 30-minute UTC buckets: 48 over the 1D window
SPARK_LIMIT = 48


def _away_from_zero(value: float) -> float:
    """``Double.rounded(.toNearestOrAwayFromZero)``, exact (Decimal of a double is exact)."""
    return float(Decimal(value).quantize(Decimal(1), rounding=ROUND_HALF_UP))


def two_places(value: float) -> float:
    """``FleetMarketHeadline.twoPlaces``: half away from zero on ``value * 100``, then / 100."""
    rounded = _away_from_zero(value * 100) / 100
    return 0.0 if rounded == 0 else rounded


def text(value: float) -> str:
    """``String(format: "%.2f", twoPlaces(value))``."""
    return "%.2f" % two_places(value)


def milliseconds(time: float) -> int:
    """``Int64((date.timeIntervalSince1970 * 1000).rounded())``."""
    return int(_away_from_zero(since1970(time) * 1000))


def spark(mean: Sequence[tuple[float, float]]) -> list[float]:
    """The mean's last value per 30-minute UTC bucket, oldest first, the newest 48, 2 places."""
    buckets: list[list[float]] = []
    for time, value in mean:
        bucket = math.floor(float(milliseconds(time)) / float(SPARK_BUCKET_MS))
        if buckets and buckets[-1][0] == bucket:
            buckets[-1][1] = value
        else:
            buckets.append([bucket, value])
    return [two_places(value) for _, value in buckets[-SPARK_LIMIT:]]


def headline(index: Index, now: float) -> dict[str, Any] | None:
    """The Live Activity ``market_index`` object, or None when the index has no mean point.

    ``value`` is the mean's last point (the Market widget's number), ``change_pct`` is
    ``latest - 100``, both rounded and printed as Swift does; ``stale`` is
    ``FleetMarketIndex.isStale`` at ``now``.
    """
    if not index.mean:
        return None
    last_time, latest = index.mean[-1]
    return {
        "value": text(latest),
        "change_pct": text(latest - 100),
        "stale": index.is_stale(now),
        "spark": spark(index.mean),
        "pairs": len(index.pairs),
        "expected": len(index.requested),
        "as_of_ms": milliseconds(last_time),
    }
