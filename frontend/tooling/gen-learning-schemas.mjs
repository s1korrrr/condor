/**
 * Generates src/v5/learning-projection-schemas.ts from the vendored frozen appendix
 * (../condor/v5/schemas/learning_projection). The schemas are never edited by hand:
 *   node tooling/gen-learning-schemas.mjs          write
 *   node tooling/gen-learning-schemas.mjs --check  fail when the generated module is out of date
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../condor/v5/schemas/learning_projection');
const target = resolve(here, '../src/v5/learning-projection-schemas.ts');

export function generate() {
  const names = readdirSync(source).filter(name => name.endsWith('.schema.json')).sort();
  const digest = createHash('sha256');
  const entries = names.map(name => {
    const bytes = readFileSync(join(source, name));
    digest.update(name).update('\0').update(bytes);
    const document = JSON.parse(bytes.toString('utf8'));
    return `  ${JSON.stringify(document.$id)}: ${JSON.stringify(document)},`;
  });
  return [
    '// GENERATED by tooling/gen-learning-schemas.mjs from condor/v5/schemas/learning_projection. Do not edit.',
    '// The appendix is frozen (rsibot 1d8c0ab6); a change is a new contract, not an edit here.',
    `export const PROJECTION_SCHEMA_SOURCE_SHA256 = ${JSON.stringify(digest.digest('hex'))};`,
    'export const PROJECTION_SCHEMAS: Record<string, unknown> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = generate();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(target, 'utf8'); } catch { /* missing */ }
    if (current !== next) { console.error('learning-projection-schemas.ts is out of date; run tooling/gen-learning-schemas.mjs'); process.exit(1); }
  } else writeFileSync(target, next);
}
